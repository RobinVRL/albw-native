#!/usr/bin/env python3
"""Write native/compilefix/func_<USA>.c from the linked stage-2 text with the lost third store
of a stack Vec3 restored (class: BOOT_LOG 102 [3d]).

  python3 tools/fix_lost_vec3.py <USA> <first frame var> <second frame var> <EU evidence>

The two named albw_frame #defines must be consecutive words (frame + o, + o + 4) loaded from
`B + K` and `B + K + 4`; a third #define `<second>_z` at frame + o + 8 and the store
`= *(undefined4 *)(B + K + 8)` are added after the second load (every occurrence)."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
usa, va, vb, evidence = sys.argv[1].upper(), sys.argv[2], sys.argv[3], sys.argv[4]
src = None
for sub in ("ghidra_analyzed5_v4",):
    p = os.path.join(ROOT, "build/decomp/ghidra_fallback", sub, usa[:3], "func_%s.c" % usa)
    if os.path.exists(p):
        src = p
assert src, "no stage-2 text for " + usa
s = open(src).read()
md = re.search(r"#define %s \(\*\((\w+ \*)\)\(albw_frame \+ (0x[0-9a-f]+|\d+)\)\)" % re.escape(vb), s)
assert md, "no frame define for " + vb
off = int(md.group(2), 0) + 4
vz = vb + "_z"
s = s.replace(md.group(0), md.group(0) + "\n  #define %s (*(undefined4 *)(albw_frame + %#x))   /* lost Vec3 z store */" % (vz, off), 1)
n = 0
def add(m):
    global n
    n += 1
    base, k = m.group(2), int(m.group(3), 0)
    return m.group(0) + "\n%s%s = *(undefined4 *)(%s + %#x);" % (m.group(1), vz, base, k + 4)
s = re.sub(r"^(\s*)%s = \*\(\w+ \*\)\((\w+) \+ (0x[0-9a-f]+|\d+)\);" % re.escape(vb), add, s, flags=re.M)
assert n, "no load of " + vb
hdr = ("/* USA %s: converted stage-2 text (%s) with one fix:\n"
       " * the lost third store of a stack Vec3 passed by address (class BOOT_LOG 102 [3d], lostframe):\n"
       " * %s.\n * Generated by tools/fix_lost_vec3.py; confidence high (instruction-level). */\n"
       % (usa, os.path.relpath(src, ROOT), evidence))
out = os.path.join(ROOT, "native/compilefix/func_%s.c" % usa)
assert not os.path.exists(out), out + " exists"
open(out, "w").write(hdr + s)
print("wrote", os.path.relpath(out, ROOT), "(%d stores added)" % n)
