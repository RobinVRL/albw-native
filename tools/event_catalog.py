#!/usr/bin/env python3
"""Catalogue of the game's scripted sequences (event flowcharts), read from YOUR ROM.

  tools/event_catalog.py [rom.3ds] [-o native/SCRIPTED_EVENTS.md]     (rom default: $ALBW_ROM)

World/Byaml/FlowChart.byaml indexes every event flowchart: Table.File (flowchart files),
Table.Entry (entry point name -> file) and Load (which flowcharts each kind of area loads). The
output is a checklist: one row per flowchart file with its areas and entry points, plus a status
column kept from the previous file (verified / broken / -) so re-running does not lose results.
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def romfs_files(rom):
    f = open(rom, "rb")
    h = f.read(0x200)
    base = struct.unpack_from("<I", h, 0x120)[0] * 0x200
    f.seek(base)
    n = f.read(0x200)
    rf = struct.unpack_from("<I", n, 0x1B0)[0] * 0x200 + base
    f.seek(rf)
    iv = f.read(0x60)
    mh = struct.unpack_from("<I", iv, 8)[0]
    bs = 1 << struct.unpack_from("<I", iv, 0x4C)[0]
    l3 = rf + ((0x60 + mh + bs - 1) // bs) * bs

    def rd(o, k):
        f.seek(l3 + o)
        return f.read(k)
    hdr = struct.unpack("<10I", rd(0, 40))
    dm, fm, fdo = rd(hdr[3], hdr[4]), rd(hdr[7], hdr[8]), hdr[9]

    def dpath(o):
        parts = []
        while o:
            p, _, _, _, _, nl = struct.unpack_from("<6I", dm, o)
            parts.append(dm[o + 24:o + 24 + nl].decode("utf-16le"))
            o = p
        return "/".join(reversed(parts))
    o = 0
    while o < len(fm):
        p, _, doff, dsz, _, nl = struct.unpack_from("<IIQQII", fm, o)
        yield dpath(p) + "/" + fm[o + 32:o + 32 + nl].decode("utf-16le"), (lambda d=doff, s=dsz: rd(fdo + d, s))
        o = (o + 32 + nl + 3) & ~3


def byaml(b):
    """little-endian BYAML v1 (dict / array / string / int / float / bool)"""
    u32 = lambda o: struct.unpack_from("<I", b, o)[0]

    def strtab(o):
        if not o:
            return []
        n = u32(o) >> 8
        return [b[o + u32(o + 4 + 4 * i):b.index(b"\0", o + u32(o + 4 + 4 * i))].decode("utf-8", "replace") for i in range(n)]
    K, S = strtab(u32(4)), strtab(u32(8))

    def node(t, v):
        if t == 0xA0: return S[v]
        if t == 0xD0: return bool(v)
        if t == 0xD1: return struct.unpack("<i", struct.pack("<I", v))[0]
        if t == 0xD2: return struct.unpack("<f", struct.pack("<I", v))[0]
        if t in (0xC0, 0xC1): return cont(v)
        return None

    def cont(o):
        t, n = b[o], u32(o) >> 8
        if t == 0xC0:
            vo = o + 4 + ((n + 3) & ~3)
            return [node(b[o + 4 + i], u32(vo + 4 * i)) for i in range(n)]
        return {K[u32(o + 4 + 8 * i) & 0xFFFFFF]: node(b[o + 7 + 8 * i], u32(o + 8 + 8 * i)) for i in range(n)}
    return cont(u32(12))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    out = os.path.join(ROOT, "native", "SCRIPTED_EVENTS.md")
    if "-o" in sys.argv:
        out = sys.argv[sys.argv.index("-o") + 1]
        args = [a for a in args if a != out]
    rom = args[0] if args else os.environ.get("ALBW_ROM")
    if not rom:
        sys.exit("usage: tools/event_catalog.py <rom.3ds> (or set ALBW_ROM)")
    y = next(byaml(get()) for p, get in romfs_files(rom) if p.endswith("World/Byaml/FlowChart.byaml"))
    files, entries, load = y["Table"]["File"], y["Table"]["Entry"], y["Load"]
    status = {}
    if os.path.exists(out):
        for l in open(out):
            m = re.match(r"^\| `([^`]+)` \| ([^|]*) \|", l)
            if m:
                status[m.group(1)] = m.group(2).strip()
    by_file = {i: [] for i in range(len(files))}
    for name, i in entries:
        by_file[i].append(name)
    areas = {f: sorted(k for k, v in load.items() if f in v and not k.startswith("Test")) for f in files}
    rows = []
    for i, f in sorted(enumerate(files), key=lambda x: x[1]):
        test_only = not areas[f] and any(f in v for v in load.values())
        rows.append("| `%s` | %s | %s | %d | %s |" % (
            f, status.get(f, "-"), ", ".join(areas[f]) or ("(test stages only)" if test_only else "(loaded on demand)"),
            len(by_file[i]), ", ".join(sorted(by_file[i]))))
    with open(out, "w") as o:
        o.write("# Scripted sequences (event flowcharts)\n\n"
                "Generated by `tools/event_catalog.py` from the ROM's World/Byaml/FlowChart.byaml: %d flowchart "
                "files, %d entry points. Status: `verified` (played through in the port, give the BOOT_LOG entry), "
                "`broken` (+ BOOT_LOG entry), `-` (not checked yet). Status is kept when the file is regenerated.\n\n"
                "| Flowchart | Status | Loaded in | Entries | Entry points |\n|---|---|---|---|---|\n"
                % (len(files), len(entries)))
        o.write("\n".join(rows) + "\n")
    print("wrote %s (%d flowcharts, %d entries)" % (out, len(files), len(entries)))


if __name__ == "__main__":
    main()
