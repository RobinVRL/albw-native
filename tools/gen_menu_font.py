#!/usr/bin/env python3
"""Generate native/platform/menu_font.h: an 8-bit alpha atlas of printable ASCII (32..126) for the
Esc menu overlay (native/platform/menu.c), 16 x 6 cells of MENU_FONT_W x MENU_FONT_H pixels;
cell 95 (char 127) is solid white (rectangles). Run once; the header is checked in.

  python3 tools/gen_menu_font.py [font.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont
W, H, SIZE = 10, 20, 16
path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/noto/NotoSansMono-Regular.ttf'
font = ImageFont.truetype(path, SIZE)
img = Image.new('L', (16 * W, 6 * H), 0)
d = ImageDraw.Draw(img)
asc, desc = font.getmetrics()
for c in range(32, 128):
    i = c - 32
    x, y = (i % 16) * W, (i // 16) * H
    if c == 127:
        d.rectangle([x, y, x + W - 1, y + H - 1], fill=255)
        continue
    d.text((x, y + (H - asc - desc) // 2), chr(c), fill=255, font=font)
data = img.tobytes()
out = ['/* generated by tools/gen_menu_font.py from %s (%dpx): do not edit */' % (path.split('/')[-1], SIZE),
       '#define MENU_FONT_W %d' % W, '#define MENU_FONT_H %d' % H,
       '#define MENU_FONT_ATLAS_W %d' % (16 * W), '#define MENU_FONT_ATLAS_H %d' % (6 * H),
       'static const unsigned char menu_font_atlas[%d] = {' % len(data)]
for k in range(0, len(data), 24):
    out.append('    ' + ','.join(str(b) for b in data[k:k + 24]) + ',')
out.append('};')
open('native/platform/menu_font.h', 'w').write('\n'.join(out) + '\n')
img.save('/tmp/menu_font_preview.png') if '--preview' in sys.argv else None
